vim.opt.runtimepath:prepend(vim.fn.getcwd())
local plugin = require('forth-stack')
local display = require('forth-stack.display')
local config = require('forth-stack.config')
local live = require('forth-stack.live')
plugin.setup({ debounce_ms = 40 })
local directory = vim.fn.tempname()
vim.fn.mkdir(directory, 'p')
local path = directory .. '/auto.fs'
vim.fn.writefile({ '10 20 +' }, path)
local function marks()
  return vim.api.nvim_buf_get_extmarks(0, display.cursor_namespace, 0, -1, { details = true })
end
local function move(col)
  vim.api.nvim_win_set_cursor(0, { 1, col })
  vim.api.nvim_exec_autocmds('CursorMoved', { buffer = 0 })
end
local function ready()
  assert(vim.wait(4000, function() return plugin.status() == 'updated' end, 10),
    vim.api.nvim_buf_get_name(0) .. ': ' .. tostring(plugin.status()) .. ' ' .. tostring(select(2, plugin.status())))
end
local ok, err = pcall(function()
  assert(config.options.auto_start and not config.options.inline)
  vim.cmd.edit(path)
  vim.cmd.ForthStackInline()
  ready()
  vim.wait(100)
  assert(#marks() == 1, 'A pending automatic run replaced the one-shot display')
  assert(live.entry(vim.api.nvim_get_current_buf()) == '')
  move(0)
  assert(#marks() == 0, 'Inline must default to off')
  vim.cmd.ForthStackInline()
  assert(marks()[1][4].virt_text[1][1] == ' [ 10 ] ')
  assert(not config.options.inline)
  move(3)
  assert(#marks() == 0, 'One-shot survived cursor movement')
  vim.cmd.ForthStackInlineToggle()
  assert(marks()[1][4].virt_text[1][1] == ' [ 10, 20 ] ')
  move(6)
  assert(marks()[1][4].virt_text[1][1] == ' [ 30 ] ')
  vim.cmd.ForthStackInlineToggle()
  assert(#marks() == 0)
  vim.cmd.ForthStackAutoToggle()
  assert(not config.options.auto_start and live.entry(vim.api.nvim_get_current_buf()) == nil)
  vim.api.nvim_buf_set_lines(0, 0, -1, false, { '3 4 +' })
  vim.wait(150)
  assert(plugin.status() ~= 'updated')
  vim.cmd.ForthStackInline() -- no trace available, run once without arming updates
  ready()
  assert(#marks() == 1)
  assert(live.entry(vim.api.nvim_get_current_buf()) == nil)
  move(0)
  assert(#marks() == 0)
  vim.cmd.ForthStackAutoToggle()
  ready()
  assert(live.entry(vim.api.nvim_get_current_buf()) == '', 'Auto toggle did not resume updates')
  vim.api.nvim_buf_set_lines(0, 0, -1, false, { '8 9 +' })
  ready()
  local end_marks = vim.api.nvim_buf_get_extmarks(0, display.namespace, 0, -1, { details = true })
  assert(end_marks[1][4].virt_text[1][1] == '[ 17 ]  after +')
  vim.cmd.ForthStackStop()
  vim.api.nvim_exec_autocmds('BufEnter', { buffer = 0 })
  vim.wait(150)
  assert(plugin.status() == 'paused', 'Entering a paused buffer restarted it')
  vim.cmd('edit!')
  vim.wait(150)
  assert(plugin.status() ~= 'updated', 'Reloading a paused buffer restarted tracing')
  assert(live.entry(vim.api.nvim_get_current_buf()) == nil)
  plugin.setup({ auto_start = false })
  vim.fn.writefile({ '1 2 +' }, directory .. '/manual.fs')
  vim.cmd.edit(directory .. '/manual.fs')
  vim.wait(150)
  assert(plugin.status() == 'inactive', 'Disabled auto-start still ran a file')
  plugin.setup({ auto_update = false })
  vim.fn.writefile({ '5 6 +' }, directory .. '/once.fs')
  vim.cmd.edit(directory .. '/once.fs')
  ready()
  assert(live.entry(vim.api.nvim_get_current_buf()) == nil)
  vim.api.nvim_buf_set_lines(0, 0, -1, false, { '5 7 +' })
  vim.wait(150)
  assert(#vim.api.nvim_buf_get_extmarks(0, display.namespace, 0, -1, {}) == 0,
    'auto_update=false still refreshed after an edit')
  plugin.setup({ inline = true, auto_start = false })
  vim.cmd.ForthStackRun()
  ready()
  move(0)
  assert(#marks() == 1, 'inline=true was ignored')
  print('PASS default auto-start, inline off, one-shot, per-buffer toggle, session toggle, pause and manual configuration')
end)
vim.fn.delete(directory, 'rf')
if not ok then print(err); vim.cmd('cquit 1') else vim.cmd('qa!') end
