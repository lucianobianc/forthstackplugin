vim.opt.runtimepath:prepend(vim.fn.getcwd())
local symbolic = require('forth-stack.symbolic')
local display = require('forth-stack.display')
local function analyze(code) return symbolic.analyze(vim.split(code, '\n', { plain = true })) end
local function event(result, row)
  local history = assert(result.lines[row], 'No observation on line ' .. row)
  return history[#history]
end
local function shown(result, row) return display.observation(event(result, row), 16) end
local passed = 0
local function test(name, callback) callback(); passed = passed + 1; print('PASS ' .. name) end
local ok, err = pcall(function()
  test('known zero nonzero and calculated values resolve ?dup without alternatives', function()
    for _, case in ipairs({ { '0 ?dup', '[ 0 ]' }, { '5 ?dup', '[ 5, 5 ]' },
      { '2 3 + ?dup', '[ 5, 5 ]' }, { '3 3 - ?dup', '[ 0 ]' },
      { '2 3 < ?dup', '[ -1, -1 ]' }, { '#10 $a - ?dup', '[ 0 ]' } }) do
      local result = analyze(': test ( -- ... )\n' .. case[1] .. '\n;')
      assert(#result.diagnostics == 0 and shown(result, 2) == case[2], vim.inspect(result))
    end
  end)
  test('unknown ?dup preserves the prefix and continues through each alternative', function()
    local result = analyze(': test ( age n -- ... )\n?dup\n1+\n;')
    assert(#result.diagnostics == 0)
    assert(shown(result, 2) == '[ age, 0 ] | [ age, n, n ]')
    assert(shown(result, 3) == '[ age, 1 ] | [ age, n, (n + 1) ]')
    local copies = analyze(': test ( n -- ... )\ndup ?dup\n?dup\n;')
    assert(shown(copies, 2) == '[ 0, 0 ] | [ n, n, n ]')
    assert(shown(copies, 3) == '[ 0, 0 ] | [ n, n, n, n ]')
  end)
  test('branch conditions refine copied symbols and known conditions skip unreachable operations', function()
    local result = analyze(': test ( n -- ... )\ndup if ?dup else ?dup then\n;')
    assert(#result.diagnostics == 0 and shown(result, 2) == '[ n, n ] | [ 0 ]')
    local predicate = analyze(': test ( n -- ... )\ndup 0= if ?dup else ?dup then\n;')
    assert(shown(predicate, 2) == '[ 0 ] | [ n, n ]')
    local known = analyze(': test ( -- out )\n0 if 1 2 + else 9 then\n?dup drop\n;')
    assert(#known.diagnostics == 0 and shown(known, 3) == '[ 9 ]')
  end)
  test('underflow on one alternative warns and retains only safe continuations', function()
    local result = analyze(': test ( n -- ... )\n?dup\n+\n1+\n;')
    assert(#result.diagnostics == 1 and result.diagnostics[1].message:find('1 of 2 alternatives fail', 1, true))
    assert(shown(result, 3) == '[ (n + n) ]' and event(result, 3).valid_paths_only)
    assert(shown(result, 4) == '[ ((n + n) + 1) ]')
    local all = analyze(': test ( -- ... )\ndrop\n5\n;')
    assert(#all.diagnostics == 1 and not all.lines[2] and not all.lines[3])
  end)
  test('variable outputs and explicitly alternative contracts do not invent fixed depths', function()
    local flexible = analyze(': test ( n -- ... ) ?dup ;')
    assert(#flexible.diagnostics == 0 and shown(flexible, 1) == '[ 0 ] | [ n, n ]')
    local declared = analyze(': test ( n -- 0 | n n ) ?dup ;')
    assert(#declared.diagnostics == 0 and shown(declared, 1) == '[ 0 ] | [ n, n ]')
    local mismatch = analyze(': test ( n -- n n ) ?dup ;')
    assert(#mismatch.diagnostics == 1 and mismatch.diagnostics[1].severity == vim.diagnostic.severity.WARN)
    local unknown = analyze(': test ( n -- ... )\n?dup\nmystery\n1+ ;')
    assert(unknown.diagnostics[1].message:find('Effect unknown', 1, true))
    assert(not unknown.lines[3] and not unknown.lines[4])
  end)
  test('supported callee bodies propagate constants without borrowing caller values for their own annotations', function()
    local result = analyze(': add-one ( n -- n ) 1+ ;\n: caller ( -- ... ) 4 add-one ?dup ;')
    assert(#result.diagnostics == 0 and shown(result, 2) == '[ 5, 5 ]')
    assert(shown(result, 1) == '[ n ]')
    local variable = analyze(': maybe ( n -- ... ) ?dup ;\n: caller ( -- ... ) 0 maybe ;')
    assert(#variable.diagnostics == 0 and shown(variable, 2) == '[ 0 ]')
    local bad_contract = analyze(': maybe ( n -- n ) ?dup ;\n: caller ( -- ... ) 5 maybe ;')
    assert(#bad_contract.diagnostics == 1 and shown(bad_contract, 2) == '[ 5, 5 ]')
    local rebound = analyze(': source ( -- n ) 1 ;\n: saved ( -- n ) source ;\n: source ( -- n ) 2 ;\n: caller ( -- ... ) saved ?dup ;')
    assert(shown(rebound, 4) == '[ 1, 1 ]')
    local contract = analyze(': external ( n -- n ) mystery ;\n: caller ( -- ... ) 5 external ?dup ;')
    assert(event(contract, 2).assumed and shown(contract, 2) == '[ 0 ] | [ n, n ]')
  end)
  test('native dot-quote preserves data and does not tokenize its string as code', function()
    local result = analyze(': hello ( -- )\n." Hello : fake ( n -- ... ) ?dup ; world"\n;')
    assert(#result.diagnostics == 0 and shown(result, 2) == '[ ]')
    local known = analyze(': test ( -- n n ) 5 ." hello" ?dup ;')
    assert(#known.diagnostics == 0 and shown(known, 1) == '[ 5, 5 ]')
    local redefine = analyze(': ." ( n -- ) drop ;\n: test ( n -- ) ." ;')
    assert(#redefine.diagnostics == 0 and shown(redefine, 2) == '[ ]')
    local opaque = analyze(': ." mystery ;\n: test ( n -- n ) ." ;')
    assert(opaque.diagnostics[1].message:find('Effect unknown', 1, true))
    local unfinished = analyze(': test ( -- ) ." unfinished\n;')
    assert(#unfinished.diagnostics > 0)
  end)
  test('constant propagation respects bases precision and does not fold unknown contracts as identities', function()
    local hex = analyze('hex\n: test ( -- ... ) 10 ?dup ;')
    assert(shown(hex, 2) == '[ 16, 16 ]')
    local wide = analyze(': test ( -- ... ) 9007199254740991 1 + ?dup ;')
    assert(#event(wide, 1).alternatives == 2, 'Rounded a result outside the safe range')
    local unknown = analyze(': f ( n -- n ) mystery ;\n: test ( -- ... ) 5 f ?dup ;')
    assert(#event(unknown, 2).alternatives == 2 and event(unknown, 2).assumed)
  end)
  test('alternative budgets stop explicitly and long presentations summarize without changing analysis', function()
    local result = analyze(': fan ( n -- ... )\n' .. string.rep('?dup 1+ ', 17) .. '\n;')
    assert(result.diagnostics[1].message:find('alternative limit reached (16 paths)', 1, true))
    local chain = { ': f0 ( n -- n ) noop ;' }
    for n = 1, 18 do chain[#chain + 1] = ': f' .. n .. ' ( n -- n ) f' .. (n - 1) .. ' ;' end
    local deep = analyze(table.concat(chain, '\n'))
    assert(deep.diagnostics[1].message:find('nesting limit', 1, true))
    local many = analyze(': large ( -- ... ) ' .. string.rep('noop ', 10001) .. ';')
    assert(many.diagnostics[1].message:find('observation budget reached', 1, true))
    local within = analyze(': fan ( n -- ... )\n' .. string.rep('?dup 1+ ', 6) .. '\n;')
    assert(#within.diagnostics == 0)
    local e = event(within, 2)
    assert(#e.alternatives > 4 and display.observation(e):find('alternatives; depth', 1, true))
    assert(not display.observation(e, 16):find('alternatives; depth', 1, true))
  end)
  test('constant results match actual Gforth for representative arithmetic and control flow', function()
    for _, body in ipairs({ '0 ?dup', '5 ?dup', '2 3 + ?dup', '6 3 / ?dup', '2 3 < ?dup',
      '5 3 and ?dup', '0 invert ?dup', '5 2 lshift ?dup', '16 2 rshift ?dup',
      '9007199254740989 7 / ?dup', '9007199254740989 7 mod ?dup', '0 if 7 else 8 then ?dup', '1 if 7 else 8 then ?dup', '8 3 mod 1+ ?dup', '0 1- abs ?dup' }) do
      local result = analyze(': sample ( -- ... ) ' .. body .. ' ;')
      assert(#result.diagnostics == 0 and #event(result, 1).alternatives == 1)
      local execution = vim.system({ 'gforth', '-e', ': sample ' .. body .. ' ; sample decimal .s bye' }, { text = true }):wait()
      assert(execution.code == 0, execution.stderr)
      local values = assert(execution.stdout:match('<%d+>%s*(.-)%s*$'))
      local actual = {}; for n in values:gmatch('%S+') do actual[#actual + 1] = n end
      assert(vim.deep_equal(event(result, 1).stack, actual), body .. ': ' .. vim.inspect(result))
    end
  end)
end)
if not ok then print(err); vim.cmd('cquit 1') else print(passed .. ' alternative-analysis tests passed'); vim.cmd('qa!') end
