vim.opt.runtimepath:prepend(vim.fn.getcwd())
local plugin = require('forth-stack')
local engine = require('forth-stack.engine')
local display = require('forth-stack.display')
local dir = vim.fn.tempname()
vim.fn.mkdir(dir, 'p')
local path = dir .. '/live.fs'
vim.fn.writefile({ ': sample 1 ;' }, path)
vim.cmd('edit ' .. vim.fn.fnameescape(path))
local buf = vim.api.nvim_get_current_buf()
local notifications, starts, passed = {}, 0, 0
vim.notify = function(msg) notifications[#notifications + 1] = msg end
local original_run = engine.run
engine.run = function(...)
  starts = starts + 1
  return original_run(...)
end
local function check(value, message) assert(value, message) end
local function test(name, callback)
  callback(); passed = passed + 1; print('PASS ' .. name)
end
local function edit(text) vim.api.nvim_buf_set_lines(buf, 0, -1, false, { text }) end
local function wait_for(callback, message)
  check(vim.wait(4000, callback, 10), message)
end
local function text()
  local marks = vim.api.nvim_buf_get_extmarks(buf, display.namespace, 0, -1, { details = true })
  return marks[1] and marks[1][4].virt_text[1][1]
end
local function updated(value)
  wait_for(function() return text() == '[ ' .. value .. ' ]  após ' .. value end,
    'resultado não atualizado: ' .. tostring(plugin.status(buf)))
end
local ok, err = pcall(function()
  plugin.setup({ debounce_ms = 120, timeout = 0.3 })
  test('Run arma atualização automática e alterações não salvas atualizam', function()
    plugin.run('sample', buf)
    updated(1)
    edit(': sample 2 ;')
    updated(2)
    check(vim.bo[buf].modified, 'buffer foi salvo')
    check(vim.fn.readfile(path)[1] == ': sample 1 ;', 'arquivo foi alterado no disco')
  end)
  test('debounce agrupa edições rápidas em uma execução', function()
    local count = starts
    edit(': sample 3 ;')
    edit(': sample 4 ;')
    edit(': sample 5 ;')
    check(starts == count, 'executou sincronicamente em on_lines')
    updated(5)
    check(starts == count + 1, 'mais de uma execução para a rajada')
  end)
  test('código incompleto não notifica a cada tecla e recupera sozinho', function()
    local count = #notifications
    edit(': sample missing-token')
    wait_for(function() return plugin.status(buf) == 'erro' end, 'erro não registrado')
    check(#notifications == count and text() == nil, 'erro automático exibiu resultado ou popup')
    local _, detail = plugin.status(buf)
    check(detail and detail:find('Execução falhou', 1, true), 'detalhe de erro ausente')
    edit(': sample 6 ;')
    updated(6)
    check(select(2, plugin.status(buf)) == nil, 'erro anterior persistiu')
  end)
  test('Stop cancela timer já pendente e pausa novas edições', function()
    edit(': sample 7 ;')
    local count = starts
    plugin.stop(buf)
    vim.wait(300, function() return false end)
    check(starts == count, 'timer disparou depois de Stop')
    edit(': sample 8 ;')
    vim.wait(300, function() return false end)
    check(starts == count and text() == nil, 'Stop não pausou auto-update')
  end)
  test('Run retoma e uma nova entrada substitui a anterior', function()
    edit(': sample 9 ; : other 10 ;')
    plugin.run('sample', buf)
    updated(9)
    edit(': sample 11 ; : other 12 ;')
    plugin.run('other', buf)
    updated(12)
    local count = starts
    vim.wait(300, function() return false end)
    check(starts == count, 'timer da entrada anterior sobreviveu')
  end)
  test('execução antiga é cancelada e próxima edição mostra somente resultado novo', function()
    edit(': other begin again ;')
    wait_for(function() return engine.running(buf) end, 'loop não iniciou')
    edit(': other 13 ;')
    check(not engine.running(buf), 'edição não cancelou processo anterior')
    updated(13)
    vim.wait(400, function() return false end)
    check(text() == '[ 13 ]  após 13', 'resposta antiga substituiu nova')
  end)
  test('recarregar do disco acompanha o novo texto', function()
    vim.fn.writefile({ ': other 20 ;' }, path)
    vim.cmd('edit!')
    updated(20)
    -- Stop issued immediately after a reload must cancel queued reattachment too.
    vim.cmd('edit!')
    plugin.stop(buf)
    local count = starts
    vim.wait(250, function() return false end)
    check(starts == count, 'reattach reativou execução após Stop')
    plugin.run('other', buf)
    updated(20)
  end)
  test('Clear pausa atualização até novo Run', function()
    plugin.clear(buf)
    local count = starts
    edit(': other 14 ;')
    vim.wait(300, function() return false end)
    check(starts == count and text() == nil, 'Clear não desarmou timer')
  end)
  test('modo manual permite buffer modificado sem reexecutar ao editar', function()
    plugin.setup({ auto_update = false, debounce_ms = 80 })
    plugin.run('other', buf)
    updated(14)
    local count = starts
    edit(': other 15 ;')
    vim.wait(250, function() return false end)
    check(starts == count and text() == nil, 'modo manual reexecutou')
  end)
  test('arquivo novo nomeado funciona sem criar o arquivo em disco', function()
    plugin.setup({ debounce_ms = 80 })
    vim.cmd('enew!')
    local newpath = dir .. '/new.fs'
    vim.api.nvim_buf_set_name(0, newpath)
    buf = vim.api.nvim_get_current_buf()
    edit(': sample 16 ;')
    plugin.run('sample', buf)
    updated(16)
    check(vim.fn.filereadable(newpath) == 0, 'arquivo novo foi escrito')
    edit(': sample 17 ;')
    updated(17)
  end)
  test('renomear/fechar desarma timers e não reexecuta em outro arquivo', function()
    edit(': sample 18 ;')
    vim.api.nvim_buf_set_name(buf, dir .. '/renamed.fs')
    local count = starts
    vim.wait(250, function() return false end)
    check(starts == count, 'renomeação manteve timer')
    plugin.run('sample', buf)
    updated(18)
    edit(': sample 19 ;')
    vim.api.nvim_buf_delete(buf, { force = true })
    vim.wait(250, function() return false end)
    check(not engine.running(buf), 'buffer fechado manteve processo')
  end)
end)
vim.fn.delete(dir, 'rf')
if not ok then vim.api.nvim_err_writeln(tostring(err)); vim.cmd('cquit 1') end
print(passed .. ' testes de atualização automática passaram')
vim.cmd('qa!')
