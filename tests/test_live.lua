vim.opt.runtimepath:prepend(vim.fn.getcwd())
local plugin = require('forth-stack')
local engine = require('forth-stack.engine')
local display = require('forth-stack.display')
local dir = vim.fn.tempname()
vim.fn.mkdir(dir, 'p')
local path = dir .. '/live.fs'
vim.fn.writefile({ ': sample 1 ;' }, path)
vim.cmd('edit ' .. vim.fn.fnameescape(path))
local buf = vim.api.nvim_get_current_buf()
local notifications, starts, passed = {}, 0, 0
vim.notify = function(msg) notifications[#notifications + 1] = msg end
local original_run = engine.run
engine.run = function(...)
  starts = starts + 1
  return original_run(...)
end
local function check(value, message) assert(value, message) end
local function test(name, callback)
  callback(); passed = passed + 1; print('PASS ' .. name)
end
local function edit(text) vim.api.nvim_buf_set_lines(buf, 0, -1, false, { text }) end
local function wait_for(callback, message)
  check(vim.wait(4000, callback, 10), message)
end
local function text()
  local marks = vim.api.nvim_buf_get_extmarks(buf, display.namespace, 0, -1, { details = true })
  return marks[1] and marks[1][4].virt_text[1][1]
end
local function updated(value)
  wait_for(function() return text() == '[ ' .. value .. ' ]  after ' .. value end,
    'Result was not updated: ' .. tostring(plugin.status(buf)))
end
local ok, err = pcall(function()
  plugin.setup({ debounce_ms = 120, timeout = 0.3 })
  test('Run enables automatic updates and unsaved edits refresh the display', function()
    plugin.run('sample', buf)
    updated(1)
    edit(': sample 2 ;')
    updated(2)
    check(vim.bo[buf].modified, 'Buffer was saved')
    check(vim.fn.readfile(path)[1] == ': sample 1 ;', 'File changed on disk')
  end)
  test('debounce groups rapid edits into one execution', function()
    local count = starts
    edit(': sample 3 ;')
    edit(': sample 4 ;')
    edit(': sample 5 ;')
    check(starts == count, 'Executed synchronously in on_lines')
    updated(5)
    check(starts == count + 1, 'More than one execution for a burst of edits')
  end)
  test('incomplete code recovers automatically without notification spam', function()
    local count = #notifications
    edit(': sample missing-token')
    wait_for(function() return plugin.status(buf) == 'error' end, 'Error was not recorded')
    check(#notifications == count and text() == nil, 'Automatic failure displayed a result or popup')
    local _, detail = plugin.status(buf)
    check(detail and detail:find('Execution failed', 1, true), 'Missing error details')
    edit(': sample 6 ;')
    updated(6)
    check(select(2, plugin.status(buf)) == nil, 'Previous error persisted')
  end)
  test('Stop cancels pending timers and pauses updates', function()
    edit(': sample 7 ;')
    local count = starts
    plugin.stop(buf)
    vim.wait(300, function() return false end)
    check(starts == count, 'Timer fired after Stop')
    edit(': sample 8 ;')
    vim.wait(300, function() return false end)
    check(starts == count and text() == nil, 'Stop did not pause automatic updates')
  end)
  test('Run resumes updates and a new entry replaces the previous one', function()
    edit(': sample 9 ; : other 10 ;')
    plugin.run('sample', buf)
    updated(9)
    edit(': sample 11 ; : other 12 ;')
    plugin.run('other', buf)
    updated(12)
    local count = starts
    vim.wait(300, function() return false end)
    check(starts == count, 'Previous entry timer survived')
  end)
  test('old execution is canceled and the next edit displays only the new result', function()
    edit(': other begin again ;')
    wait_for(function() return engine.running(buf) end, 'Loop did not start')
    edit(': other 13 ;')
    check(not engine.running(buf), 'Editing did not cancel the previous process')
    updated(13)
    vim.wait(400, function() return false end)
    check(text() == '[ 13 ]  after 13', 'Old response replaced the new result')
  end)
  test('reloading from disk tracks the new text', function()
    vim.fn.writefile({ ': other 20 ;' }, path)
    vim.cmd('edit!')
    updated(20)
    -- Stop issued immediately after a reload must cancel queued reattachment too.
    vim.cmd('edit!')
    plugin.stop(buf)
    local count = starts
    vim.wait(250, function() return false end)
    check(starts == count, 'Reattachment restarted execution after Stop')
    plugin.run('other', buf)
    updated(20)
  end)
  test('Clear pauses updates until the next Run', function()
    plugin.clear(buf)
    local count = starts
    edit(': other 14 ;')
    vim.wait(300, function() return false end)
    check(starts == count and text() == nil, 'Clear did not disarm the timer')
  end)
  test('manual mode supports unsaved buffers without rerunning on edits', function()
    plugin.setup({ auto_update = false, debounce_ms = 80 })
    plugin.run('other', buf)
    updated(14)
    local count = starts
    edit(': other 15 ;')
    vim.wait(250, function() return false end)
    check(starts == count and text() == nil, 'Manual mode reran automatically')
  end)
  test('new named buffers work without creating files on disk', function()
    plugin.setup({ debounce_ms = 80 })
    vim.cmd('enew!')
    local newpath = dir .. '/new.fs'
    vim.api.nvim_buf_set_name(0, newpath)
    buf = vim.api.nvim_get_current_buf()
    edit(': sample 16 ;')
    plugin.run('sample', buf)
    updated(16)
    check(vim.fn.filereadable(newpath) == 0, 'New file was written to disk')
    edit(': sample 17 ;')
    updated(17)
  end)
  test('renaming or closing disarms timers without executing another file', function()
    edit(': sample 18 ;')
    vim.api.nvim_buf_set_name(buf, dir .. '/renamed.fs')
    local count = starts
    vim.wait(250, function() return false end)
    check(starts == count, 'Renaming retained the timer')
    plugin.run('sample', buf)
    updated(18)
    edit(': sample 19 ;')
    vim.api.nvim_buf_delete(buf, { force = true })
    vim.wait(250, function() return false end)
    check(not engine.running(buf), 'Closed buffer retained its process')
  end)
end)
vim.fn.delete(dir, 'rf')
if not ok then vim.api.nvim_err_writeln(tostring(err)); vim.cmd('cquit 1') end
print(passed .. ' automatic-update tests passed')
vim.cmd('qa!')
