vim.opt.runtimepath:prepend(vim.fn.getcwd())
local plugin = require('forth-stack')
local display = require('forth-stack.display')
plugin.setup({ debounce_ms = 80 })
local dir = vim.fn.tempname()
vim.fn.mkdir(dir, 'p')
vim.cmd.enew()
vim.api.nvim_buf_set_name(0, dir .. '/new.fs')
local buf = vim.api.nvim_get_current_buf()
local function edit(lines) vim.api.nvim_buf_set_lines(buf, 0, -1, false, lines) end
local function marks()
  local result = {}
  for _, m in ipairs(vim.api.nvim_buf_get_extmarks(buf, display.namespace, 0, -1, { details = true })) do
    result[m[2] + 1] = m[4].virt_text[1][1]
  end
  return result
end
local function wait_for(predicate)
  assert(vim.wait(4000, predicate, 10), 'Result did not appear: ' .. tostring(select(2, plugin.status(buf))))
end
local ok, err = pcall(function()
  edit({ ': can-drive ( age -- f ) 18 >= ;', '', '18 can-drive', '20 can-drive' })
  vim.cmd.ForthStackRun()
  wait_for(function() return marks()[4] == '[ -1, -1 ]  after can-drive' end)
  assert(marks()[3] == '[ -1 ]  after can-drive')
  assert(marks()[1] == nil, 'Definition displayed a stack from a later call')
  assert(vim.fn.filereadable(dir .. '/new.fs') == 0, 'Execution wrote the source file')
  print('PASS file mode shows call-site stacks without projecting them onto definitions')
  edit({ ': can-drive ( age -- f ) 18 >= ;', '', '18 can-drive', '17 can-drive' })
  wait_for(function() return marks()[4] == '[ -1, 0 ]  after can-drive' end)
  print('PASS unsaved edits preserve file mode and update stacks')
  plugin.stop(buf)
  edit({ ': specific 99 ;', '1 2 +' })
  plugin.run('specific', buf)
  wait_for(function() return marks()[1] == '[ 3, 99 ]  after 99' end)
  vim.cmd.ForthStackRun()
  wait_for(function() return marks()[2] == '[ 3 ]  after +' and marks()[1] == nil end)
  print('PASS Run without arguments switches to file mode without invoking the previous entry')
  edit({ ': specific 99 ;' })
  wait_for(function() return plugin.status(buf) == 'updated' end)
  assert(vim.tbl_isempty(marks()), 'Uncalled definition displayed an invented stack')
  print('PASS definitions-only file does not execute bodies or produce an error')
  edit({ ': birthday 1 + ;', ': can-drive 18 >= ;',
    '10 ( LABEL: age ) can-drive', '20 can-drive',
    '16 ( LABEL: age ) birthday', 'dup can-drive', 'over birthday', 'can-drive' })
  wait_for(function() return marks()[8] == '[ 0, -1, age:17, 0, -1 ]  after can-drive' end)
  assert(marks()[1] == nil and marks()[2] == nil,
    'Future calls leaked their stacks onto definition lines')
  assert(marks()[3] == '[ 0 ]  after can-drive')
  assert(marks()[5] == '[ 0, -1, age:17 ]  after birthday')
  local win = plugin.inspect(buf, 1)
  local detail = table.concat(vim.api.nvim_buf_get_lines(vim.api.nvim_win_get_buf(win), 0, -1, false), '\n')
  assert(detail:find('Context: last call', 1, true))
  vim.api.nvim_win_close(win, true)
  vim.api.nvim_win_set_cursor(0, { 1, 13 })
  plugin.inline_once()
  local cursor = vim.api.nvim_buf_get_extmarks(buf, display.cursor_namespace, 0, -1, { details = true })
  assert(#cursor == 1 and cursor[1][4].virt_text[2][1]:find('last call', 1, true))
  print('PASS screenshot regression: chronological call-site stacks and explicit last-call inspection')
  edit({ '10 : later 1+ ;', 'later' })
  wait_for(function() return marks()[2] == '[ 11 ]  after later' end)
  assert(marks()[1] == '[ 10 ]  after 10', 'Later body event replaced the earlier top-level state')
  edit({ ': plus-one', '  1 +', '; 16 plus-one' })
  wait_for(function() return marks()[3] == '[ 17 ]  after plus-one' end)
  assert(marks()[1] == nil and marks()[2] == nil,
    'Multiline definition displayed future state')
  print('PASS mixed lines preserve top-level observations and multiline definitions stay unannotated')

end)
plugin.stop(buf)
vim.api.nvim_buf_delete(buf, { force = true })
vim.fn.delete(dir, 'rf')
if not ok then vim.api.nvim_err_writeln(tostring(err)); vim.cmd('cquit 1') end
print('6 file-mode tests passed')
vim.cmd('qa!')
