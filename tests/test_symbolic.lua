vim.opt.runtimepath:prepend(vim.fn.getcwd())
local symbolic = require('forth-stack.symbolic')
local passed = 0
local function test(name, callback)
  callback(); passed = passed + 1; print('PASS ' .. name)
end
local function analyze(text)
  return symbolic.analyze(vim.split(text, '\n', { plain = true }))
end
local function stack(result, line)
  local history = assert(result.lines[line])
  return table.concat(history[#history].stack, ',')
end
local ok, err = pcall(function()
  test('documented input names and output names are independent of callers', function()
    local result = analyze(': can-drive ( idade -- pode-dirigir )\n18\n>=\n;\n10 can-drive\n20 can-drive')
    assert(stack(result, 2) == 'idade,18')
    assert(stack(result, 3) == 'pode-dirigir')
    assert(not result.lines[5] and #result.diagnostics == 0)
    local three = analyze(': process ( nome idade cpf -- status )\ndrop\nnip\n18 >=\n;')
    assert(stack(three, 2) == 'nome,idade')
    assert(stack(three, 3) == 'idade')
    assert(stack(three, 4) == 'status')
  end)
  test('stack operators keep symbolic identities and user contracts compose', function()
    local result = analyze(': birthday ( age -- older ) 1+ ;\n: pair ( age -- age older ) dup birthday ;')
    assert(stack(result, 2) == 'age,older')
    local preserve = analyze(': unchanged ( x -- x ) ;\n: example ( age -- age age ) dup unchanged ;')
    assert(stack(preserve, 2) == 'age,age')
  end)
  test('permutations and drops preserve ordered input symbols without sparse stacks', function()
    local expected = { dup = 'a,b,c,c', drop = 'a,b', swap = 'a,c,b', over = 'a,b,c,b',
      rot = 'b,c,a', nip = 'a,c', tuck = 'a,c,b,c', ['2dup'] = 'a,b,c,b,c', ['2drop'] = 'a' }
    for op, value in pairs(expected) do
      local outputs = value:gsub(',', ' ')
      local result = analyze(': test ( a b c -- ' .. outputs .. ' )\n' .. op .. '\nnoop ;')
      assert(#result.diagnostics == 0 and stack(result, 2) == value, op)
    end
  end)
  test('mismatched outputs and insufficient documented inputs warn', function()
    local result = analyze(': wrong ( n -- result ) dup ;')
    assert(result.diagnostics[1].message:find('Stack effect mismatch', 1, true))
    assert(stack(result, 1) == 'n,n')
    local under = analyze(': wrong ( -- result ) 18 >= ;')
    assert(under.diagnostics[1].message:find('too few cells', 1, true))
    assert(under.diagnostics[1].severity == vim.diagnostic.severity.WARN)
  end)
  test('simple conditionals join equal depths and report incompatible branches', function()
    local result = analyze(': choose ( flag -- value ) if 1 else 2 then ;')
    assert(#result.diagnostics == 0 and stack(result, 1) == '1')
    local invalid = analyze(': choose ( flag -- value ) if 1 else 2 3 then ;')
    assert(invalid.diagnostics[1].message:find('different stack depths', 1, true))
    local nested = analyze(': choose ( a b -- value ) if if 1 else 2 then else drop 3 then ;')
    assert(#nested.diagnostics == 0 and stack(nested, 1) == '1')
  end)
  test('unknown words loops recursion and variable effects stop conservatively', function()
    for _, body in ipairs({ 'mystery', 'begin', 'recurse', 's" hello"', '10.' }) do
      local result = analyze(': example ( x -- x )\n' .. body .. '\n1+ ;')
      assert(#result.diagnostics > 0, body)
      assert(not result.lines[3], 'Invented state beyond ' .. body)
    end
    local recursive = analyze(': example ( x -- x ) example ;')
    assert(recursive.diagnostics[1].message:find('Recursive', 1, true))
  end)
  test('comments strings and redefined primitives cannot invent definitions or effects', function()
    local result = analyze('\\ : fake ( -- x ) 10 ;\ns" : fake ( -- x ) 20 ;"\n: dup ( -- n ) 7 ;\n: use ( -- n ) dup ;')
    assert(not result.lines[1] and not result.lines[2])
    assert(stack(result, 4) == '7')
    local unknown = analyze(': dup 7 ;\n: use ( -- n ) dup ;')
    assert(#unknown.diagnostics == 1)
  end)
  test('dictionary changes and immediate words stop dependent analysis', function()
    local included = analyze('include external.fs\n: example ( x -- x ) 1+ ;')
    assert(included.diagnostics[1].message:find('Dictionary-changing', 1, true))
    assert(not next(included.lines))
    local immediate = analyze(': macro ( x -- x ) 1+ ; immediate\n: example ( x -- x ) macro ;')
    assert(immediate.diagnostics[1].message:find('No usable stack effect', 1, true))
    local quoted = analyze("' :\nchar :\n.( : fake ( -- x ) 1 ; )\n: actual ( n -- n ) noop ;")
    assert(not quoted.lines[1] and not quoted.lines[2] and not quoted.lines[3])
    assert(stack(quoted, 4) == 'n')
  end)
  test('source token and symbolic depth limits return notices without inventing states', function()
    local too_large = analyze(string.rep('x', 4 * 1024 * 1024 + 1))
    assert(#too_large.diagnostics == 1 and not next(too_large.lines))
    local too_many = analyze(string.rep('noop ', 50001))
    assert(#too_many.diagnostics == 1 and not next(too_many.lines))
    local names = {}
    for n = 1, 256 do names[n] = 'x' .. n end
    local depth = analyze(': limit ( ' .. table.concat(names, ' ') .. ' -- result )\ndup ;')
    assert(depth.diagnostics[1].message:find('exceeds 256', 1, true))
    assert(not depth.lines[2])
  end)
  test('unsupported contracts and incomplete definitions are explicit', function()
    for _, text in ipairs({ ': test ( F: x -- y ) 1+ ;', ': test ( x ... -- y ) dup ;', ': test ( n -- n ) dup' }) do
      local result = analyze(text)
      assert(#result.diagnostics == 1 and not next(result.lines))
    end
    assert(not next(analyze(': undocumented 1+ ;').lines))
  end)
end)
if not ok then print(err); vim.cmd('cquit 1') else print(passed .. ' symbolic analysis tests passed'); vim.cmd('qa!') end
