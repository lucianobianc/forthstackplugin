vim.opt.runtimepath:prepend(vim.fn.getcwd())
local plugin = require('forth-stack')
local symbolic = require('forth-stack.symbolic')
local display = require('forth-stack.display')
local diagnostic = require('forth-stack.diagnostics')
plugin.setup({ auto_start = false, debounce_ms = 60 })
local dir = vim.fn.tempname()
vim.fn.mkdir(dir, 'p')
vim.cmd.enew()
vim.api.nvim_buf_set_name(0, dir .. '/example.fs')
local buf = vim.api.nvim_get_current_buf()
local other = vim.api.nvim_create_namespace('other-plugin-diagnostics')
vim.diagnostic.set(other, buf, {{ lnum = 0, col = 0, message = 'Other diagnostic' }})
local notifications = {}
vim.notify = function(message) notifications[#notifications + 1] = message end
local function edit(lines) vim.api.nvim_buf_set_lines(buf, 0, -1, false, lines) end
local function wait_status(expected)
  assert(vim.wait(5000, function() return plugin.status(buf) == expected end, 10),
    tostring(plugin.status(buf)) .. ': ' .. tostring(select(2, plugin.status(buf))))
end
local function marks(namespace)
  return vim.api.nvim_buf_get_extmarks(buf, namespace, 0, -1, { details = true })
end
local function symbolic_text(line)
  for _, mark in ipairs(marks(symbolic.namespace)) do
    if mark[2] == line - 1 then return mark[4].virt_text[1][1] end
  end
end
local passed = 0
local function test(name, callback) callback(); passed = passed + 1; print('PASS ' .. name) end
local ok, err = pcall(function()
  test('uncalled definitions show documented symbols, with zero runtime inputs', function()
    edit({ ': can-drive ( age -- status )', '18', '>=', ';' })
    plugin.run()
    wait_status('updated')
    assert(symbolic_text(1) == '[ age ]  symbolic inputs')
    assert(symbolic_text(2) == '[ age, 18 ]  symbolic')
    assert(symbolic_text(3) == '[ status ]  symbolic')
    assert(#marks(display.namespace) == 0)
    local win = plugin.inspect(buf, 2)
    local text = table.concat(vim.api.nvim_buf_get_lines(vim.api.nvim_win_get_buf(win), 0, -1, false), '\n')
    assert(text:find('Stack: [ age, 18 ]', 1, true) and text:find('Analysis: symbolic', 1, true))
    vim.api.nvim_win_close(win, true)
  end)
  test('underflow points at the call, keeps symbols and only successful partial states', function()
    edit({ ': can-drive ( age -- status ) 18 >= ;', '9 drop', 'can-drive' })
    wait_status('error')
    local errors = vim.diagnostic.get(buf, { namespace = diagnostic.namespace })
    assert(#errors == 1 and errors[1].severity == vim.diagnostic.severity.ERROR)
    assert(errors[1].lnum == 2 and errors[1].col == 0 and errors[1].end_col == 9, vim.inspect(errors))
    assert(errors[1].message:find('Stack underflow', 1, true))
    assert(symbolic_text(1) == '[ status ]  symbolic')
    local partial = marks(display.namespace)
    assert(#partial == 1 and partial[1][2] == 1)
    assert(partial[1][4].virt_text[1][1] == '[ ]  after drop')
    assert(partial[1][4].virt_text[2][1]:find('before error', 1, true))
    assert(#notifications == 0, 'Automatic failure opened a popup')
    vim.api.nvim_win_set_cursor(0, { 2, 0 })
    plugin.inline_once()
    local cursor = marks(display.cursor_namespace)
    assert(cursor[1][4].virt_text[2][1]:find('before error', 1, true))
    local win = plugin.inspect(buf, 2)
    local detail = table.concat(vim.api.nvim_buf_get_lines(vim.api.nvim_win_get_buf(win), 0, -1, false), '\n')
    assert(detail:find('Execution incomplete', 1, true))
    vim.api.nvim_win_close(win, true)
    local trace = { format_version = 1, status = 'forth_error', complete = false, events = {} }
    assert(not pcall(plugin.show, trace, buf), 'A failed trace import was accepted')
  end)
  test('fixing a call clears errors and partial markers without contaminating symbols', function()
    edit({ ': can-drive ( age -- status ) 18 >= ;', '20 can-drive' })
    wait_status('updated')
    assert(#vim.diagnostic.get(buf, { namespace = diagnostic.namespace }) == 0)
    assert(symbolic_text(1) == '[ status ]  symbolic')
    local runtime = marks(display.namespace)
    assert(#runtime == 1 and runtime[1][4].virt_text[1][1] == '[ -1 ]  after can-drive')
    assert(#runtime[1][4].virt_text == 1)
  end)
  test('contract mismatches warn without falsely claiming a correct result', function()
    edit({ ': wrong ( n -- result ) dup ;' })
    wait_status('updated')
    local warnings = vim.diagnostic.get(buf, { namespace = symbolic.diagnostics })
    assert(#warnings == 1 and warnings[1].severity == vim.diagnostic.severity.WARN)
    assert(symbolic_text(1) == '[ n, n ]  symbolic')
  end)
  test('unknown runtime word gets a diagnostic and an unsupported body stays incomplete', function()
    edit({ ': custom ( x -- x ) mystery ;' })
    wait_status('error')
    assert(#vim.diagnostic.get(buf, { namespace = diagnostic.namespace }) == 1)
    assert(#vim.diagnostic.get(buf, { namespace = symbolic.diagnostics }) == 1)
    assert(symbolic_text(1) == '[ x ]  symbolic inputs')
  end)
  test('symbolic analysis works before executable validation and clear removes owned diagnostics', function()
    plugin.stop()
    plugin.setup({ auto_start = false, gforth = 'not-installed-gforth' })
    edit({ ': can-drive ( age -- status ) 18 >= ;' })
    vim.cmd.ForthStackAnalyze()
    assert(plugin.status() == 'analyzed' and not require('forth-stack.engine').running(buf))
    assert(symbolic_text(1) == '[ status ]  symbolic')
    assert(not pcall(plugin.run))
    assert(symbolic_text(1) == '[ status ]  symbolic')
    plugin.setup({ auto_start = false, symbolic = false })
    plugin.run()
    wait_status('updated')
    assert(#marks(symbolic.namespace) == 0, 'symbolic=false was ignored')
    plugin.clear()
    assert(#marks(symbolic.namespace) == 0)
    assert(#vim.diagnostic.get(buf, { namespace = diagnostic.namespace }) == 0)
    assert(#vim.diagnostic.get(buf, { namespace = symbolic.diagnostics }) == 0)
    assert(#vim.diagnostic.get(buf, { namespace = other }) == 1, 'Another plugin diagnostic was removed')
  end)
end)
plugin.clear()
vim.fn.delete(dir, 'rf')
if not ok then print(err); vim.cmd('cquit 1') else print(passed .. ' analysis/diagnostic integration tests passed'); vim.cmd('qa!') end
