vim.opt.runtimepath:prepend(vim.fn.getcwd())
local plugin = require('forth-stack')
local display = require('forth-stack.display')
local symbolic = require('forth-stack.symbolic')
plugin.setup({ auto_start = false, inline = true })
vim.cmd.enew()
local buf = vim.api.nvim_get_current_buf()
vim.api.nvim_buf_set_name(buf, vim.fn.tempname() .. '.fs')
vim.api.nvim_buf_set_lines(buf, 0, -1, false, {
  ': keep ( n -- n )', 'dup drop', ';', '4 5 +', '7 noop',
})
local function marks(namespace)
  return vim.api.nvim_buf_get_extmarks(buf, namespace, 0, -1, { details = true })
end
local function point(row, col)
  vim.api.nvim_win_set_cursor(0, { row, col })
  vim.api.nvim_exec_autocmds('CursorMoved', { buffer = buf })
  return marks(display.cursor_namespace)
end
local ok, err = pcall(function()
  plugin.run()
  assert(vim.wait(5000, function() return plugin.status() == 'updated' end, 10))
  local tick = vim.api.nvim_buf_get_changedtick(buf)
  assert(#point(4, 0) == 1, 'Earlier literal lost its inline stack')
  assert(#point(4, 4) == 0, 'Final runtime observation was duplicated')
  assert(#marks(display.namespace) == 2, 'Final end-of-line stacks disappeared')
  assert(#point(2, 0) == 1, 'Earlier symbolic operation lost its inline stack')
  assert(#point(2, 4) == 0, 'Final symbolic observation was duplicated')
  assert(#marks(symbolic.namespace) == 2)
  assert(#point(5, 0) == 1, 'Equal values at a different token must still be inspectable')
  assert(#point(5, 2) == 0)
  assert(#point(4, 4) == 0)
  plugin.inline_once()
  assert(#marks(display.cursor_namespace) == 0, 'One-shot duplicated an existing final stack')
  plugin.toggle()
  assert(#marks(display.namespace) == 0 and #marks(symbolic.namespace) == 0)
  plugin.inline_once()
  assert(#marks(display.cursor_namespace) == 1, 'Hidden end-of-line text suppressed a one-shot')
  point(4, 2)
  assert(#marks(display.cursor_namespace) == 0)
  plugin.toggle()
  assert(#point(4, 4) == 0)
  assert(#point(4, 0) == 1, 'Moving back did not restore inline display')
  assert(vim.api.nvim_buf_get_changedtick(buf) == tick)
  local mixed = '10 : inc ( n -- n ) 1+ ; inc'
  vim.api.nvim_buf_set_lines(buf, 0, -1, false, { mixed })
  plugin.run('inc')
  assert(vim.wait(5000, function() return plugin.status() == 'updated' end, 10))
  local ending = marks(display.namespace)
  assert(#ending == 1 and ending[1][4].virt_text[1][1] == '[ 11 ]  after inc',
    'Mixed symbolic/runtime line lost its end-of-line call state')
  assert(#marks(symbolic.namespace) == 0)
  assert(#point(1, #mixed - 3) == 0)
  assert(#point(1, mixed:find('1+', 1, true) - 1) == 1)
  print('PASS final runtime and symbolic stacks are not duplicated; earlier tokens, one-shot and hidden views still work')
end)
plugin.clear()
if not ok then print(err); vim.cmd('cquit 1') else vim.cmd('qa!') end
